-- ভোটার তালিকা সাইটের ডাটাবেস টেবিল (install.php স্বয়ংক্রিয়ভাবে চালায়)
CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL DEFAULT '',
  pass_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','user') NOT NULL DEFAULT 'user',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS remember_tokens (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  selector CHAR(18) NOT NULL UNIQUE,
  validator_hash CHAR(64) NOT NULL,
  expires_at DATETIME NOT NULL,
  INDEX (user_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ip VARCHAR(45) NOT NULL,
  username VARCHAR(50) NOT NULL DEFAULT '',
  at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (ip, at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(40) PRIMARY KEY,
  v TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS activity_log (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NULL,
  action VARCHAR(30) NOT NULL,
  detail VARCHAR(255) NOT NULL DEFAULT '',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ভোটার এলাকা (ওয়ার্ড + লিঙ্গভিত্তিক অংশ)
CREATE TABLE IF NOT EXISTS sections (
  id INT UNSIGNED PRIMARY KEY,
  gender VARCHAR(10) NOT NULL,
  area_no VARCHAR(10) NOT NULL,
  area_name VARCHAR(150) NOT NULL,
  ward VARCHAR(5) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voters (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  sl INT UNSIGNED NOT NULL,
  vno VARCHAR(20) NOT NULL,
  name VARCHAR(150) NOT NULL,
  father VARCHAR(150) NOT NULL DEFAULT '',
  mother VARCHAR(150) NOT NULL DEFAULT '',
  prof VARCHAR(100) NOT NULL DEFAULT '',
  dob VARCHAR(20) NOT NULL DEFAULT '',
  dob_date DATE NULL,
  addr VARCHAR(400) NOT NULL DEFAULT '',
  section_id INT UNSIGNED NOT NULL,
  page INT UNSIGNED NOT NULL DEFAULT 0,
  gender VARCHAR(10) NOT NULL,
  ward VARCHAR(5) NOT NULL,
  area_no VARCHAR(10) NOT NULL,
  first_name VARCHAR(60) NOT NULL DEFAULT '',
  last_name VARCHAR(60) NOT NULL DEFAULT '',
  house VARCHAR(150) NOT NULL DEFAULT '',
  dup TINYINT(1) NOT NULL DEFAULT 0,
  n_name VARCHAR(150) NOT NULL DEFAULT '',
  n_father VARCHAR(150) NOT NULL DEFAULT '',
  n_mother VARCHAR(150) NOT NULL DEFAULT '',
  n_addr VARCHAR(400) NOT NULL DEFAULT '',
  n_dob VARCHAR(20) NOT NULL DEFAULT '',
  n_prof VARCHAR(100) NOT NULL DEFAULT '',
  n_all TEXT NOT NULL,
  INDEX (vno), INDEX (ward), INDEX (area_no), INDEX (gender), INDEX (prof), INDEX (dob_date),
  INDEX dupkey (n_name(60), n_father(60), n_dob)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
